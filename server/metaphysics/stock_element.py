class StockElementAnalyzer:
    """股票名称五行分析器。"""

    @staticmethod
    def char_element(ch: str) -> str | None:
        """单个汉字的五行属性。"""
        return CHAR_ELEMENT.get(ch)

    @classmethod
    def name_elements(cls, name: str) -> list[str]:
        """分析股票名称中每个字符的五行。"""
        elements = []
        for ch in name:
            e = cls.char_element(ch)
            if e:
                elements.append(e)
        return elements

    @classmethod
    def dominant_element(cls, name: str) -> str | None:
        """股票名称的主五行（出现次数最多的）。"""
        elements = cls.name_elements(name)
        if not elements:
            return None
        counter = Counter(elements)
        return counter.most_common(1)[0][0]

    @classmethod
    def element_profile(cls, name: str) -> dict[str, int]:
        """股票名称的五行分布。"""
        elements = cls.name_elements(name)
        return dict(Counter(elements))

    @classmethod
    def score_by_element(cls, name: str, target_element: str) -> float:
        """
        计算股票名称对某目标五行的匹配得分 (0~1)。

        得分逻辑：
        - 名称中目标五行字符占比越高，得分越高
        - 名称中"生目标"五行的字符也加分（通关）
        - 名称中"克目标"五行的字符减分
        """
        from .elements import GENERATE, RESTRAIN, GENERATED_BY

        elements = cls.name_elements(name)
        if not elements:
            return 0.0

        total = len(elements)
        target_generates = GENERATE.get(target_element)  # 我生
        target_generated_by = GENERATED_BY.get(target_element)  # 生我
        target_restrains = RESTRAIN.get(target_element)  # 我克
        target_restrained_by = {v: k for k, v in RESTRAIN.items()}.get(target_element)  # 克我

        score = 0.0
        for e in elements:
            if e == target_element:
                score += 1.0  # 同气
            elif e == target_generated_by:
                score += 0.8  # 生我者（印）
            elif e == target_generates:
                score += 0.3  # 我生者（食伤，泄气但通关）
            elif e == target_restrained_by:
                score -= 0.5  # 克我者（官杀）
            elif e == target_restrains:
                score -= 0.2  # 我克者（财，耗气）

        return round(score / total, 3)

    @classmethod
    def industry_element(cls, industry: str) -> str | None:
        """根据行业名称判断五行。"""
        return INDUSTRY_ELEMENT.get(industry)

    @classmethod
    def keyword_element(cls, name: str) -> str | None:
        """根据股票名称中的关键词判断五行。"""
        for keyword, element in NAME_KEYWORD_ELEMENT.items():
            if keyword in name:
                return element
        return None

    @classmethod
    def combined_element(cls, name: str, industry: str | None = None) -> str | None:
        """
        综合判断股票五行属性：
        1. 优先行业五行
        2. 其次名称关键词
        3. 最后名称字符统计
        """
        if industry:
            ie = cls.industry_element(industry)
            if ie:
                return ie
        ke = cls.keyword_element(name)
        if ke:
            return ke
        return cls.dominant_element(name)
